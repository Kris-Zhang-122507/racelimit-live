import { chromium } from "playwright";
const O = process.env.OUT || "shots"; (await import("node:fs")).mkdirSync(O, { recursive: true });
const b = await chromium.launch({ executablePath: process.env.CHROMIUM || "/opt/pw-browsers/chromium", args: ["--headless=new", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const p = await b.newPage({ viewport: { width: 1440, height: 860 } });
const errs = []; p.on("pageerror", (e) => errs.push("ERR " + e.message)); p.on("console", (m) => { if (m.type() === "error") errs.push(m.text()); });
await p.goto(`${process.env.BASE || "http://localhost:8791/"}race/index.html`);
await p.waitForSelector(".mm-card.hero", { timeout: 60000 }); await p.waitForTimeout(1500);
await p.screenshot({ path: `${O}/m1.png` });
await p.click(".mm-card.hero"); await p.waitForSelector(".mm-track", { timeout: 20000 });
await p.click('.mm-track[data-id="interlagos"]'); await p.waitForTimeout(2500);
await p.screenshot({ path: `${O}/m2.png` });
await p.click(".mm-side .btn.primary");
await p.waitForFunction(() => window.__race && document.getElementById("loading").hidden, null, { timeout: 240000 });
const f0 = await p.evaluate(() => window.__race.frames); while ((await p.evaluate(() => window.__race.frames)) < f0 + 3) await p.waitForTimeout(400);
const st = await p.evaluate(() => { const c = window.__race.c; return { onPit: c.onPit, pidx: c.pidx, kmh: c.u * 3.6, tyres: c.tyres?.map((t) => t.temp), compound: c.compound, lap: window.__race.T.lap, out: window.__race.T.outLap }; });
console.log(JSON.stringify(st));
await p.screenshot({ path: `${O}/m3.png`, timeout: 240000 });
console.log([...new Set(errs)].slice(0, 6).join("\n"));
await b.close();
